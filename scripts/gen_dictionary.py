"""
Seed a dictionary.yaml from local sources, to make starting easier.

It extracts only IDENTIFIERS (domains, IPs/CIDRs, emails, the machine hostname,
and the org/host from a git remote). It deliberately does NOT write credentials,
tokens or hashes to the file — those are caught dynamically by the regex layer,
and a dictionary is not a place to store secrets.

Output goes to dictionary.generated.yaml for you to review and merge — it never
overwrites your real dictionary.yaml.

Usage:
    python scripts/gen_dictionary.py --from .env --from /etc/nginx/sites-enabled/app
    python scripts/gen_dictionary.py --from .env --git --hostname
"""
import argparse
import os
import re
import socket
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from anonproxy import regex_detector  # noqa: E402

# Only these detector types become dictionary entries (never secrets).
_TYPE_TO_SECTION = {
    "DOMAIN": "domains",
    "IP_ADDRESS": "ips",
    "CIDR": "cidrs",
    "EMAIL": "emails",
}


def _from_files(paths: list[str], buckets: dict[str, set]) -> None:
    for p in paths:
        try:
            text = open(p, encoding="utf-8", errors="replace").read()
        except OSError as exc:
            print(f"  skip {p}: {exc}", file=sys.stderr)
            continue
        for val, etype in regex_detector.detect(text):
            section = _TYPE_TO_SECTION.get(etype)
            if section:
                buckets[section].add(val)


def _from_hostname(buckets: dict[str, set]) -> None:
    for name in {socket.gethostname(), socket.getfqdn()}:
        name = name.strip()
        if name and name.lower() not in ("localhost", "localhost.localdomain"):
            if "." in name:
                buckets["domains"].add(name)
            else:
                buckets["hosts"].add(name)


def _from_git(buckets: dict[str, set]) -> None:
    try:
        out = subprocess.check_output(["git", "remote", "-v"], text=True, stderr=subprocess.DEVNULL)
    except (OSError, subprocess.CalledProcessError):
        return
    for m in re.finditer(r"(?:@|//)([a-z0-9.-]+\.[a-z]{2,})[:/]([^/\s]+)/", out, re.I):
        host, org = m.group(1), m.group(2)
        if host.lower() not in ("github.com", "gitlab.com", "bitbucket.org"):
            buckets["domains"].add(host)
        buckets["organizations"].add(org)


_SECTION_ORDER = ["domains", "hosts", "ips", "cidrs", "emails",
                  "usernames", "organizations", "paths"]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--from", dest="files", action="append", default=[],
                    help="file to scan for identifiers (repeatable)")
    ap.add_argument("--git", action="store_true", help="read git remotes in CWD")
    ap.add_argument("--hostname", action="store_true", help="include this machine's hostname")
    ap.add_argument("-o", "--out", default="dictionary.generated.yaml")
    args = ap.parse_args()

    if not (args.files or args.git or args.hostname):
        ap.print_help()
        return 1

    buckets: dict[str, set] = {s: set() for s in _SECTION_ORDER}
    if args.files:
        _from_files(args.files, buckets)
    if args.hostname:
        _from_hostname(buckets)
    if args.git:
        _from_git(buckets)

    lines = [
        "# Generated by scripts/gen_dictionary.py — REVIEW before using.",
        "# Only identifiers are seeded; secrets are handled by the regex layer.",
        "# Merge the parts you want into dictionary.yaml.",
        "",
    ]
    total = 0
    for section in _SECTION_ORDER:
        vals = sorted(buckets[section])
        if not vals:
            continue
        lines.append(f"{section}:")
        for v in vals:
            lines.append(f"  - {v}")
            total += 1
        lines.append("")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {total} identifier(s) to {args.out}")
    print("Review it, then merge the relevant lines into dictionary.yaml.")
    print("Add hostnames / usernames / org / brand names and sensitive paths by hand —")
    print("those are the high-value entries a scan cannot infer reliably.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
